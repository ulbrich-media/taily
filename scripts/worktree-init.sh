#!/usr/bin/env bash
#
# Make a git worktree (e.g. Dispatch / Claude workspaces) runnable next to the main checkout.
#
# The main checkout uses fixed hosts (api.taily.ddev.site + taily.ddev.site:5544). A worktree gets its
# own DDEV project and hostnames derived from its directory name, so they can run in parallel and the
# cookie/CORS setup of the login keeps working:
#
#   main      frontend  taily.ddev.site:5544            api  api.taily.ddev.site
#   worktree  frontend  <slug>.taily.ddev.site:<port>   api  api.<slug>.taily.ddev.site
#
# Idempotent. Does nothing in the main checkout. Does not start DDEV.

set -euo pipefail

root="$(git rev-parse --show-toplevel)"
cd "$root"

main="$(git worktree list --porcelain | awk '/^worktree /{print substr($0, 10); exit}')"

if [ "$main" = "$root" ]; then
  echo "Main checkout - nothing to do."
  exit 0
fi

slug="$(basename "$root" | tr '[:upper:]' '[:lower:]' | sed -E 's/[^a-z0-9]+/-/g; s/^-+|-+$//g' | cut -c1-40 | sed -E 's/-+$//')"
host="${slug}.taily.ddev.site"
api_host="api.${host}"
port=$((5545 + $(printf '%s' "$slug" | cksum | cut -d' ' -f1) % 400))

rewrite() {
  sed -e 's#api\.taily\.ddev\.site#@API@#g' \
    -e 's#taily\.ddev\.site:5544#@HOST@:@PORT@#g' \
    -e 's#taily\.ddev\.site#@HOST@#g' \
    -e "s#@API@#${api_host}#g" \
    -e "s#@HOST@#${host}#g" \
    -e "s#@PORT@#${port}#g"
}

# First existing file wins: main checkout's real file, then the example shipped in this worktree.
render() {
  local target="$1" example="$2" source=""
  for candidate in "$main/$target" "$example"; do
    if [ -f "$candidate" ]; then source="$candidate"; break; fi
  done
  [ -n "$source" ] || return 0
  rewrite < "$source" > "$target"
  echo "Wrote $target (from ${source#"$main"/})"
}

# DDEV: own project name -> own containers, database and router hostname.
cat > .ddev/config.local.yaml <<YAML
# Generated by scripts/worktree-init.sh - not committed.
name: api.${slug}.taily
YAML
echo "Wrote .ddev/config.local.yaml (project api.${slug}.taily)"

render api/.env api/.env.example
render frontend/.env.local frontend/.env.local.example
printf 'VITE_DEV_HOST=%s\nVITE_DEV_PORT=%s\n' "$host" "$port" >> frontend/.env.local

# TLS cert for the Vite dev server (the main checkout's cert only covers taily.ddev.site).
if command -v mkcert > /dev/null 2>&1; then
  mkdir -p frontend/.cert
  mkcert -key-file frontend/.cert/key.pem -cert-file frontend/.cert/cert.pem "$host" > /dev/null 2>&1 \
    && echo "Wrote frontend/.cert for $host"
else
  echo "mkcert not found - Vite will serve plain http for $host."
fi

cat <<MSG

Worktree ready:
  API       https://${api_host}
  Frontend  https://${host}:${port}

Next:  ddev start && ddev composer install && ddev artisan migrate && npm ci --prefix frontend && npm run dev --prefix frontend
MSG
